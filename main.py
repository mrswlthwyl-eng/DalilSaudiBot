async def reply_message(update: Update, context: ContextTypes.DEFAULT_TYPE):
    if not is_authorized(update):
        log_unauthorized(update)
        await handle_unauthorized(update)
        return

    user_id = update.effective_user.id
    user_text = update.message.text.strip()

    # ============================================================
    # فلتر الردود - البوت يرد في حالتين فقط
    # ============================================================
    
    # قائمة التحيات
    greeting_words = [
        "السلام عليكم", "وعليكم السلام", "سلام", "هلا", "اهلا", "مرحبا",
        "صباح الخير", "صباح النور", "مساء الخير", "مساء النور",
        "ياهلا", "حياك", "حياكم", "hello", "hi", "hey"
    ]
    is_greeting = any(g in user_text.lower() for g in greeting_words)
    has_keyword = "دليلي" in user_text
    
    # تجاهل إذا مو تحية ومافيه دليلي
    if not is_greeting and not has_keyword:
        return
    
    # رد على التحية فقط
    if is_greeting and not has_keyword:
        if "السلام" in user_text:
            await update.message.reply_text("وعليكم السلام ورحمة الله وبركاته")
        elif "صباح" in user_text:
            await update.message.reply_text("صباح النور")
        elif "مساء" in user_text:
            await update.message.reply_text("مساء النور")
        else:
            await update.message.reply_text("أهلاً وسهلاً")
        return

    # حذف كلمة "دليلي" من النص
    user_text = user_text.replace("دليلي", "").strip()
    
    if not user_text:
        await update.message.reply_text("تفضل، كيف أقدر أساعدك؟")
        return

    # ============================================================
    # STEP 1: Knowledge Base (MUST run first)
    # ============================================================
    kb_result = knowledge.search(user_text)

    print("=" * 40)
    print(f"📝 Query : {user_text}")
    print(f"🔍 KB    : found={kb_result.get('found')}")

    if kb_result.get("found"):
        score = kb_result.get("score", 0)
        title = kb_result.get("title", "")
        
        # ✅ تجاهل النتائج العامة والضعيفة
        bad_titles = [
            "kfu_training_knowledge", "kfu_external_opportunities",
            "kfu_specific_info", "training_knowledge", "قاعدة معرفة"
        ]
        is_bad = any(bad in title for bad in bad_titles)
        
        if score >= 50 and not is_bad:
            print(f"✅ KB MATCH!")
            print(f"   Title : {kb_result.get('title')}")
            print(f"   URL   : {kb_result.get('url')}")
            print(f"   Score : {score}")
            print("=" * 40)

            lines = []
            if kb_result.get("title"):
                lines.append(f"📌 {kb_result['title']}")
            if kb_result.get("url"):
                lines.append(f"🔗 {kb_result['url']}")
            if kb_result.get("answer") and not kb_result.get("answer", "").startswith("http"):
                lines.append(kb_result["answer"])

            answer = "\n\n".join(lines)

            memory.add_user_message(user_id, user_text)
            memory.add_assistant_message(user_id, answer)
            await update.message.reply_text(answer)
            return
        else:
            print(f"⚠️ KB ignored (score={score}, title={title})")

    # ============================================================
    # STEP 2: AI Fallback (only if KB found nothing)
    # ============================================================
    print("❌ KB: no match → calling AI")
    print("=" * 40)

    history = memory.get_history(user_id)
    now = datetime.now(ZoneInfo("Asia/Riyadh"))

    try:
        hijri = Hijri.today()
        hijri_day, hijri_month, hijri_year = hijri.day, hijri.month, hijri.year
    except Exception:
        hijri_day, hijri_month, hijri_year = 1, 1, 1446

    HIJRI_MONTHS = {
        1: "محرم", 2: "صفر", 3: "ربيع الأول",
        4: "ربيع الآخر", 5: "جمادى الأولى", 6: "جمادى الآخرة",
        7: "رجب", 8: "شعبان", 9: "رمضان",
        10: "شوال", 11: "ذو القعدة", 12: "ذو الحجة",
    }
    hijri_date = f"{hijri_day} {HIJRI_MONTHS.get(hijri_month, 'محرم')} {hijri_year} هـ"

    days = {
        "Monday": "الاثنين", "Tuesday": "الثلاثاء",
        "Wednesday": "الأربعاء", "Thursday": "الخميس",
        "Friday": "الجمعة", "Saturday": "السبت", "Sunday": "الأحد",
    }
    current_day = days.get(now.strftime("%A"), now.strftime("%A"))

    current_time_context = f"""
==============================
معلومات الوقت الحالية

التاريخ الميلادي: {now.strftime("%Y-%m-%d")}
التاريخ الهجري: {hijri_date}
اليوم: {current_day}
الوقت: {now.strftime("%H:%M:%S")}
المنطقة الزمنية: Asia/Riyadh
==============================
"""

    system_prompt = SYSTEM_PROMPT + "\n\n" + current_time_context

    # ✅ أضف سياق الجامعة إذا عرفها البوت
    university_id = knowledge.find_university(user_text)
    if university_id:
        uni_context = knowledge.get_university_context_for_ai(university_id)
        if uni_context:
            system_prompt += "\n\n" + uni_context

    try:
        answer = await provider.get_response(
            system_prompt=system_prompt,
            history=history,
            user_prompt=user_text,
        )
        answer = re.sub(r"[*_`#]+", "", answer).strip()

        memory.add_user_message(user_id, user_text)
        memory.add_assistant_message(user_id, answer)
        await update.message.reply_text(answer)

    except Exception as e:
        print(f"AI Error: {e}")
        await update.message.reply_text(
            "حدثت مشكلة مؤقتة في خدمة الذكاء الاصطناعي، يرجى المحاولة مرة أخرى."
        )


